#!/usr/bin/env bash

set -Eeuo pipefail

if [[ $# != 4 ]]; then
  printf 'Usage: %s <AppImage> <AppDir> <runtime-dir> <AppImage-output-plugin>\n' "$0" >&2
  exit 2
fi

APPIMAGE="$(realpath -- "$1")"
APPDIR="$(realpath -- "$2")"
RUNTIME_DIR="$(realpath -- "$3")"
OUTPUT_PLUGIN="$(realpath -- "$4")"
REQUIRED=(
  pilo-server-windows-x86_64.exe
  pilo-server-linux-x86_64
  pilo-server-linux-aarch64
  pilo-server-darwin-aarch64
)

if [[ ! -f "$APPIMAGE" || ! -x "$APPDIR/AppRun" || ! -x "$OUTPUT_PLUGIN" ]]; then
  printf 'Missing AppImage, prepared AppDir, or executable AppImage output plugin\n' >&2
  exit 1
fi

# Locate the resource directory by its staged runtime, retaining product-name case.
mapfile -t RUNTIME_PATHS < <(find "$APPDIR/usr/lib" -type f -name pilo-server-linux-x86_64)
if [[ ${#RUNTIME_PATHS[@]} != 1 ]]; then
  printf 'Expected exactly one bundled x64 server in %s\n' "$APPDIR" >&2
  exit 1
fi
BUNDLED_RUNTIME_DIR="$(dirname -- "${RUNTIME_PATHS[0]}")"
RUNTIME_RELATIVE="${BUNDLED_RUNTIME_DIR#"$APPDIR/"}"

# linuxdeploy patches ELF resources too, corrupting our static PIE servers.
# Restore every runtime after linuxdeploy and never run it over this AppDir again.
for name in "${REQUIRED[@]}"; do
  if [[ ! -s "$RUNTIME_DIR/$name" ]]; then
    printf 'Missing original server runtime: %s\n' "$RUNTIME_DIR/$name" >&2
    exit 1
  fi
  cp -- "$RUNTIME_DIR/$name" "$BUNDLED_RUNTIME_DIR/$name"
done
chmod 755 "$BUNDLED_RUNTIME_DIR"/pilo-server-linux-* "$BUNDLED_RUNTIME_DIR/pilo-server-darwin-aarch64"

# The host Mesa/EGL stack must use its own Wayland client library.
# This library is also excluded by the upstream AppImage excludelist.
find "$APPDIR/usr/lib" -name 'libwayland-client.so*' -delete

# linuxdeploy's GTK hook forces X11, which hides KWin's per-monitor Wayland
# scale factors. Let GTK select Wayland natively while retaining its X11 fallback.
FORCED_X11_PATTERN='^[[:space:]]*export[[:space:]]+GDK_BACKEND=x11([[:space:]]*#.*)?$'
GTK_HOOK="$APPDIR/apprun-hooks/linuxdeploy-plugin-gtk.sh"
if [[ -f "$GTK_HOOK" ]]; then
  sed -i -E "/$FORCED_X11_PATTERN/d" "$GTK_HOOK"
fi

EXPECTED_FINGERPRINT="$("$RUNTIME_DIR/pilo-server-linux-x86_64" --fingerprint)"
if [[ ! "$EXPECTED_FINGERPRINT" =~ ^[0-9a-f]{16}$ ]]; then
  printf 'Original x64 server did not return a valid fingerprint\n' >&2
  exit 1
fi

WORK_DIR="$(mktemp -d)"
trap 'rm -rf -- "$WORK_DIR"' EXIT
REBUILT="$WORK_DIR/Pilo.AppImage"

# Invoke only the output plugin: calling linuxdeploy again would patch the
# restored servers. Tauri's updater signature is regenerated by the caller.
ARCH=x86_64 OUTPUT="$REBUILT" APPIMAGE_EXTRACT_AND_RUN=1 \
  "$OUTPUT_PLUGIN" --appdir "$APPDIR"
test -s "$REBUILT"
chmod 755 "$REBUILT"

# Verify the final SquashFS contents, not just the input AppDir.
mkdir "$WORK_DIR/verify"
(
  cd -- "$WORK_DIR/verify"
  "$REBUILT" --appimage-extract > /dev/null
)
EXTRACTED="$WORK_DIR/verify/squashfs-root"
if [[ -n "$(find "$EXTRACTED/usr/lib" -name 'libwayland-client.so*' -print -quit)" ]]; then
  printf 'Rebuilt AppImage still contains a bundled Wayland client library\n' >&2
  exit 1
fi
EXTRACTED_GTK_HOOK="$EXTRACTED/apprun-hooks/linuxdeploy-plugin-gtk.sh"
if [[ -f "$EXTRACTED_GTK_HOOK" ]] && grep -Eq "$FORCED_X11_PATTERN" "$EXTRACTED_GTK_HOOK"; then
  printf 'Rebuilt AppImage still forces the GTK X11 backend\n' >&2
  exit 1
fi
for name in "${REQUIRED[@]}"; do
  cmp -- "$RUNTIME_DIR/$name" "$EXTRACTED/$RUNTIME_RELATIVE/$name"
done
ACTUAL_FINGERPRINT="$("$EXTRACTED/$RUNTIME_RELATIVE/pilo-server-linux-x86_64" --fingerprint)"
if [[ "$ACTUAL_FINGERPRINT" != "$EXPECTED_FINGERPRINT" ]]; then
  printf 'Packaged x64 server fingerprint does not match the original runtime\n' >&2
  exit 1
fi

mv -- "$REBUILT" "$APPIMAGE"
printf 'Finalized AppImage: original runtimes verified, host Wayland client required\n'
