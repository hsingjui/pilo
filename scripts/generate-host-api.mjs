import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

import { writeGenerated } from "./write-generated.mjs";

const root = fileURLToPath(new URL("..", import.meta.url));
const raw = execFileSync(
	"cargo",
	["run", "--quiet", "-p", "pilo-runtime", "--example", "host_api_methods"],
	{
		cwd: root,
		encoding: "utf8",
	},
);
const data = JSON.parse(raw);

writeGenerated(
	new URL("../shared/api/host-methods.json", import.meta.url),
	data,
	"pnpm generate:host-api",
);

writeGenerated(
	new URL("../crates/pilo-cli/src/host_methods.rs", import.meta.url),
	rustBindings(data),
	"pnpm generate:host-api",
);

// The CLI calls JSON methods over local IPC; bind their names and parameters.
function rustBindings({ protocolVersion, methods }) {
	const lines = [
		"// @generated by `pnpm generate:host-api` from the Runtime method registry; do not edit.",
		"",
		"use crate::contract::{Method, Param};",
		"",
		`pub const PROTOCOL_VERSION: &str = ${JSON.stringify(protocolVersion)};`,
	];
	for (const method of methods.filter((spec) => spec.kind === "json")) {
		lines.push("");
		lines.push(`pub const ${constant(method.name)}: Method = Method {`);
		lines.push(`    name: ${JSON.stringify(method.name)},`);
		lines.push("    params: &[");
		for (const param of method.params) {
			lines.push(
				`        Param { name: ${JSON.stringify(param.name)}, ty: ${JSON.stringify(param.type)}, optional: ${param.optional} },`,
			);
		}
		lines.push("    ],");
		lines.push("};");
	}
	return lines.join("\n") + "\n";
}

function constant(name) {
	return name
		.replace(/([a-z0-9])([A-Z])/g, "$1_$2")
		.replace(/\./g, "_")
		.toUpperCase();
}
